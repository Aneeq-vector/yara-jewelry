export function getProductBySlug(slug: string): Product | undefined {
  return products.find((p) => p.slug === slug);
}

export function getProductsByCategory(category: string): Product[] {
  return products.filter((p) => p.category === category);
}

export function getTrendingProducts(): Product[] {
  return products.filter((p) => p.badge === 'trending' || p.badge === 'best-seller').slice(0, 8);
}

export function getNewArrivals(): Product[] {
  return products.filter((p) => p.badge === 'new' || p.category === 'new-arrivals').slice(0, 8);
}

export function searchProducts(query: string): Product[] {
  const lower = query.toLowerCase();
  return products.filter(
    (p) =>
      p.name.toLowerCase().includes(lower) ||
      p.shortDescription.toLowerCase().includes(lower) ||
      p.tags.some((t) => t.includes(lower)) ||
      p.category.includes(lower)
  );
}
